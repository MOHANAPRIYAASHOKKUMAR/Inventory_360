-- =============================================================================
-- Inventory 360 | Role-based access control
-- Role hierarchy:
--   SYSADMIN
--     └── INV360_ADMIN        platform owner (all objects)
--           └── INV360_ENGINEER   builds pipelines (RAW/STAGING/MARTS write)
--                 └── INV360_PLANNER   supply planners (MARTS read + APP write-back)
--                       └── INV360_VIEWER    management / read-only dashboards
-- Run as: SECURITYADMIN, then SYSADMIN for object grants
-- =============================================================================
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS INV360_ADMIN    COMMENT = 'Inventory 360 platform administrator';
CREATE ROLE IF NOT EXISTS INV360_ENGINEER COMMENT = 'Inventory 360 data engineer';
CREATE ROLE IF NOT EXISTS INV360_PLANNER  COMMENT = 'Supply / replenishment planner';
CREATE ROLE IF NOT EXISTS INV360_VIEWER   COMMENT = 'Read-only management reporting';

GRANT ROLE INV360_VIEWER   TO ROLE INV360_PLANNER;
GRANT ROLE INV360_PLANNER  TO ROLE INV360_ENGINEER;
GRANT ROLE INV360_ENGINEER TO ROLE INV360_ADMIN;
GRANT ROLE INV360_ADMIN    TO ROLE SYSADMIN;

USE ROLE SYSADMIN;

-- Warehouse
GRANT USAGE, OPERATE ON WAREHOUSE INV360_WH TO ROLE INV360_VIEWER;
GRANT MODIFY, MONITOR ON WAREHOUSE INV360_WH TO ROLE INV360_ADMIN;

-- Database
GRANT USAGE ON DATABASE INVENTORY_360_DB TO ROLE INV360_VIEWER;
GRANT ALL   ON DATABASE INVENTORY_360_DB TO ROLE INV360_ADMIN;

-- Viewer: MARTS read + APP usage
GRANT USAGE ON SCHEMA INVENTORY_360_DB.MARTS TO ROLE INV360_VIEWER;
GRANT USAGE ON SCHEMA INVENTORY_360_DB.APP   TO ROLE INV360_VIEWER;
GRANT SELECT ON ALL TABLES    IN SCHEMA INVENTORY_360_DB.MARTS TO ROLE INV360_VIEWER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA INVENTORY_360_DB.MARTS TO ROLE INV360_VIEWER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA INVENTORY_360_DB.MARTS TO ROLE INV360_VIEWER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA INVENTORY_360_DB.MARTS TO ROLE INV360_VIEWER;
GRANT SELECT ON ALL TABLES    IN SCHEMA INVENTORY_360_DB.APP   TO ROLE INV360_VIEWER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA INVENTORY_360_DB.APP   TO ROLE INV360_VIEWER;

-- Planner: write-back of replenishment decisions
GRANT INSERT, UPDATE ON ALL TABLES    IN SCHEMA INVENTORY_360_DB.APP TO ROLE INV360_PLANNER;
GRANT INSERT, UPDATE ON FUTURE TABLES IN SCHEMA INVENTORY_360_DB.APP TO ROLE INV360_PLANNER;

-- Engineer: build in RAW / STAGING / MARTS
GRANT ALL ON SCHEMA INVENTORY_360_DB.RAW     TO ROLE INV360_ENGINEER;
GRANT ALL ON SCHEMA INVENTORY_360_DB.STAGING TO ROLE INV360_ENGINEER;
GRANT ALL ON SCHEMA INVENTORY_360_DB.MARTS   TO ROLE INV360_ENGINEER;
GRANT ALL ON ALL TABLES IN SCHEMA INVENTORY_360_DB.RAW TO ROLE INV360_ENGINEER;

-- Admin: everything in APP (Streamlit, procedures, tasks)
GRANT ALL ON SCHEMA INVENTORY_360_DB.APP TO ROLE INV360_ADMIN;
GRANT CREATE STREAMLIT ON SCHEMA INVENTORY_360_DB.APP TO ROLE INV360_ADMIN;

