-- =============================================================================
-- Inventory 360 | Data-quality checks
--
-- One result set: layer, check, table, failing rows, status (PASS / WARN / FAIL).
-- Read-only. Run after loading RAW and after rebuilding STAGING / MARTS:
--   snow sql -f sql/quality/01_data_quality_checks.sql --connection <name>
-- Mirrors the dbt source tests (_sources.yml) and singular tests (dbt_inventory/tests)
-- so the checks also run where dbt cannot authenticate (SSO-only accounts).
-- =============================================================================
USE DATABASE INVENTORY_360_DB;

WITH checks (layer, check_name, table_name, failing_rows, warn_only) AS (
  -- ---------------------------------------------------------------- volume
  SELECT 'RAW', 'Table not empty', 'ERP_SUPPLIERS',            IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.ERP_SUPPLIERS
  UNION ALL SELECT 'RAW', 'Table not empty', 'WMS_WAREHOUSES', IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.WMS_WAREHOUSES
  UNION ALL SELECT 'RAW', 'Table not empty', 'ERP_PRODUCTS',   IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.ERP_PRODUCTS
  UNION ALL SELECT 'RAW', 'Table not empty', 'ERP_CUSTOMERS',  IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.ERP_CUSTOMERS
  UNION ALL SELECT 'RAW', 'Table not empty', 'WMS_STOCK_SNAPSHOT_DAILY', IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.WMS_STOCK_SNAPSHOT_DAILY
  UNION ALL SELECT 'RAW', 'Table not empty', 'POS_SALES_DAILY', IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.POS_SALES_DAILY
  UNION ALL SELECT 'RAW', 'Table not empty', 'ERP_PURCHASE_ORDER_LINES', IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.ERP_PURCHASE_ORDER_LINES
  UNION ALL SELECT 'RAW', 'Table not empty', 'TMS_SHIPMENTS',  IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.TMS_SHIPMENTS
  UNION ALL SELECT 'RAW', 'Table not empty', 'FIN_WAREHOUSE_COSTS_MONTHLY', IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.FIN_WAREHOUSE_COSTS_MONTHLY
  UNION ALL SELECT 'RAW', 'Table not empty', 'FIN_BUDGETS_MONTHLY', IFF(COUNT(*) = 0, 1, 0), FALSE FROM RAW.FIN_BUDGETS_MONTHLY

  -- ---------------------------------------------------------------- freshness (latest business date = yesterday)
  UNION ALL SELECT 'RAW', 'Fresh: latest snapshot is yesterday', 'WMS_STOCK_SNAPSHOT_DAILY',
         IFF(MAX(SNAPSHOT_DATE) >= DATEADD(day, -1, CURRENT_DATE()), 0, 1), FALSE FROM RAW.WMS_STOCK_SNAPSHOT_DAILY
  UNION ALL SELECT 'RAW', 'Fresh: latest sales day is yesterday', 'POS_SALES_DAILY',
         IFF(MAX(SALES_DATE) >= DATEADD(day, -1, CURRENT_DATE()), 0, 1), FALSE FROM RAW.POS_SALES_DAILY
  UNION ALL SELECT 'RAW', 'No future-dated snapshots', 'WMS_STOCK_SNAPSHOT_DAILY',
         COUNT_IF(SNAPSHOT_DATE >= CURRENT_DATE()), FALSE FROM RAW.WMS_STOCK_SNAPSHOT_DAILY
  UNION ALL SELECT 'RAW', 'No future-dated sales', 'POS_SALES_DAILY',
         COUNT_IF(SALES_DATE >= CURRENT_DATE()), FALSE FROM RAW.POS_SALES_DAILY

  -- ---------------------------------------------------------------- continuity (no missing days)
  UNION ALL SELECT 'RAW', 'No missing snapshot days', 'WMS_STOCK_SNAPSHOT_DAILY',
         DATEDIFF(day, MIN(SNAPSHOT_DATE), MAX(SNAPSHOT_DATE)) + 1 - COUNT(DISTINCT SNAPSHOT_DATE), FALSE
    FROM RAW.WMS_STOCK_SNAPSHOT_DAILY
  UNION ALL SELECT 'RAW', 'No missing sales days', 'POS_SALES_DAILY',
         DATEDIFF(day, MIN(SALES_DATE), MAX(SALES_DATE)) + 1 - COUNT(DISTINCT SALES_DATE), FALSE FROM RAW.POS_SALES_DAILY
  UNION ALL SELECT 'RAW', 'Latest snapshot day complete (>= 95% of 28-day median rows)', 'WMS_STOCK_SNAPSHOT_DAILY',
         IFF(MAX(IFF(d = mx, n, NULL)) >= 0.95 * MEDIAN(IFF(d > DATEADD(day, -28, mx), n, NULL)), 0, 1), FALSE
    FROM (SELECT SNAPSHOT_DATE d, COUNT(*) n, MAX(SNAPSHOT_DATE) OVER () mx
            FROM RAW.WMS_STOCK_SNAPSHOT_DAILY GROUP BY 1)

  -- ---------------------------------------------------------------- uniqueness (primary / grain keys)
  UNION ALL SELECT 'RAW', 'Unique key', 'ERP_SUPPLIERS', COUNT(*) - COUNT(DISTINCT SUPPLIER_ID), FALSE FROM RAW.ERP_SUPPLIERS
  UNION ALL SELECT 'RAW', 'Unique key', 'WMS_WAREHOUSES', COUNT(*) - COUNT(DISTINCT WAREHOUSE_CODE), FALSE FROM RAW.WMS_WAREHOUSES
  UNION ALL SELECT 'RAW', 'Unique key', 'ERP_PRODUCTS', COUNT(*) - COUNT(DISTINCT SKU), FALSE FROM RAW.ERP_PRODUCTS
  UNION ALL SELECT 'RAW', 'Unique key', 'ERP_CUSTOMERS', COUNT(*) - COUNT(DISTINCT CUSTOMER_ID), FALSE FROM RAW.ERP_CUSTOMERS
  UNION ALL SELECT 'RAW', 'Unique grain (date, site, SKU)', 'WMS_STOCK_SNAPSHOT_DAILY',
         COUNT(*) - COUNT(DISTINCT SNAPSHOT_DATE, WAREHOUSE_CODE, SKU), FALSE FROM RAW.WMS_STOCK_SNAPSHOT_DAILY
  UNION ALL SELECT 'RAW', 'Unique grain (date, site, SKU)', 'POS_SALES_DAILY',
         COUNT(*) - COUNT(DISTINCT SALES_DATE, WAREHOUSE_CODE, SKU), FALSE FROM RAW.POS_SALES_DAILY
  UNION ALL SELECT 'RAW', 'Unique key (PO, line)', 'ERP_PURCHASE_ORDER_LINES',
         COUNT(*) - COUNT(DISTINCT PO_NUMBER, PO_LINE), FALSE FROM RAW.ERP_PURCHASE_ORDER_LINES
  UNION ALL SELECT 'RAW', 'Unique key', 'TMS_SHIPMENTS', COUNT(*) - COUNT(DISTINCT SHIPMENT_ID), FALSE FROM RAW.TMS_SHIPMENTS

  -- ---------------------------------------------------------------- completeness (key columns not null)
  UNION ALL SELECT 'RAW', 'Not null keys', 'ERP_PRODUCTS',
         COUNT_IF(SKU IS NULL OR SUPPLIER_ID IS NULL OR UNIT_COST_GBP IS NULL OR UNIT_PRICE_GBP IS NULL), FALSE FROM RAW.ERP_PRODUCTS
  UNION ALL SELECT 'RAW', 'Not null keys', 'WMS_STOCK_SNAPSHOT_DAILY',
         COUNT_IF(SNAPSHOT_DATE IS NULL OR WAREHOUSE_CODE IS NULL OR SKU IS NULL OR QTY_ON_HAND IS NULL), FALSE
    FROM RAW.WMS_STOCK_SNAPSHOT_DAILY
  UNION ALL SELECT 'RAW', 'Not null keys', 'POS_SALES_DAILY',
         COUNT_IF(SALES_DATE IS NULL OR WAREHOUSE_CODE IS NULL OR SKU IS NULL OR UNITS_DEMANDED IS NULL), FALSE
    FROM RAW.POS_SALES_DAILY
  UNION ALL SELECT 'RAW', 'Not null keys', 'ERP_PURCHASE_ORDER_LINES',
         COUNT_IF(PO_NUMBER IS NULL OR SKU IS NULL OR WAREHOUSE_CODE IS NULL OR ORDER_DATE IS NULL OR PO_STATUS IS NULL), FALSE
    FROM RAW.ERP_PURCHASE_ORDER_LINES
  UNION ALL SELECT 'RAW', 'Not null keys', 'TMS_SHIPMENTS',
         COUNT_IF(SHIPMENT_ID IS NULL OR PO_NUMBER IS NULL OR SHIPMENT_STATUS IS NULL), FALSE FROM RAW.TMS_SHIPMENTS

  -- ---------------------------------------------------------------- referential integrity
  UNION ALL SELECT 'RAW', 'Product supplier exists', 'ERP_PRODUCTS', COUNT(*), FALSE
    FROM RAW.ERP_PRODUCTS p WHERE NOT EXISTS (SELECT 1 FROM RAW.ERP_SUPPLIERS s WHERE s.SUPPLIER_ID = p.SUPPLIER_ID)
  UNION ALL SELECT 'RAW', 'Customer home site exists', 'ERP_CUSTOMERS', COUNT(*), FALSE
    FROM RAW.ERP_CUSTOMERS c WHERE NOT EXISTS (SELECT 1 FROM RAW.WMS_WAREHOUSES w WHERE w.WAREHOUSE_CODE = c.HOME_WAREHOUSE_CODE)
  UNION ALL SELECT 'RAW', 'Snapshot SKU and site exist', 'WMS_STOCK_SNAPSHOT_DAILY', COUNT(*), FALSE
    FROM RAW.WMS_STOCK_SNAPSHOT_DAILY k
   WHERE NOT EXISTS (SELECT 1 FROM RAW.ERP_PRODUCTS p WHERE p.SKU = k.SKU)
      OR NOT EXISTS (SELECT 1 FROM RAW.WMS_WAREHOUSES w WHERE w.WAREHOUSE_CODE = k.WAREHOUSE_CODE)
  UNION ALL SELECT 'RAW', 'Sales SKU and site exist', 'POS_SALES_DAILY', COUNT(*), FALSE
    FROM RAW.POS_SALES_DAILY s
   WHERE NOT EXISTS (SELECT 1 FROM RAW.ERP_PRODUCTS p WHERE p.SKU = s.SKU)
      OR NOT EXISTS (SELECT 1 FROM RAW.WMS_WAREHOUSES w WHERE w.WAREHOUSE_CODE = s.WAREHOUSE_CODE)
  UNION ALL SELECT 'RAW', 'PO supplier, SKU and site exist', 'ERP_PURCHASE_ORDER_LINES', COUNT(*), FALSE
    FROM RAW.ERP_PURCHASE_ORDER_LINES l
   WHERE NOT EXISTS (SELECT 1 FROM RAW.ERP_SUPPLIERS s WHERE s.SUPPLIER_ID = l.SUPPLIER_ID)
      OR NOT EXISTS (SELECT 1 FROM RAW.ERP_PRODUCTS p WHERE p.SKU = l.SKU)
      OR NOT EXISTS (SELECT 1 FROM RAW.WMS_WAREHOUSES w WHERE w.WAREHOUSE_CODE = l.WAREHOUSE_CODE)
  UNION ALL SELECT 'RAW', 'Shipment PO exists', 'TMS_SHIPMENTS', COUNT(*), FALSE
    FROM RAW.TMS_SHIPMENTS t WHERE NOT EXISTS (SELECT 1 FROM RAW.ERP_PURCHASE_ORDER_LINES l WHERE l.PO_NUMBER = t.PO_NUMBER)

  -- ---------------------------------------------------------------- validity / business rules
  UNION ALL SELECT 'RAW', 'Units sold <= units demanded', 'POS_SALES_DAILY',
         COUNT_IF(UNITS_SOLD > UNITS_DEMANDED), FALSE FROM RAW.POS_SALES_DAILY
  UNION ALL SELECT 'RAW', 'No negative quantities or sales', 'POS_SALES_DAILY',
         COUNT_IF(UNITS_SOLD < 0 OR UNITS_DEMANDED < 0 OR NET_SALES_GBP < 0), FALSE FROM RAW.POS_SALES_DAILY
  UNION ALL SELECT 'RAW', 'No negative stock', 'WMS_STOCK_SNAPSHOT_DAILY',
         COUNT_IF(QTY_ON_HAND < 0 OR QTY_ALLOCATED < 0 OR QTY_ALLOCATED > QTY_ON_HAND), FALSE FROM RAW.WMS_STOCK_SNAPSHOT_DAILY
  UNION ALL SELECT 'RAW', 'Price above cost', 'ERP_PRODUCTS',
         COUNT_IF(UNIT_PRICE_GBP <= UNIT_COST_GBP OR UNIT_COST_GBP <= 0), FALSE FROM RAW.ERP_PRODUCTS
  UNION ALL SELECT 'RAW', 'Accepted values (velocity, lifecycle)', 'ERP_PRODUCTS',
         COUNT_IF(VELOCITY_CLASS NOT IN ('A', 'B', 'C')
                  OR LIFECYCLE_STATUS NOT IN ('Core', 'New', 'Seasonal', 'Discontinued')), FALSE FROM RAW.ERP_PRODUCTS
  UNION ALL SELECT 'RAW', 'Accepted values (PO status)', 'ERP_PURCHASE_ORDER_LINES',
         COUNT_IF(PO_STATUS NOT IN ('OPEN', 'IN_TRANSIT', 'RECEIVED')), FALSE FROM RAW.ERP_PURCHASE_ORDER_LINES
  UNION ALL SELECT 'RAW', 'Received lines have a received date and qty; others do not', 'ERP_PURCHASE_ORDER_LINES',
         COUNT_IF((PO_STATUS = 'RECEIVED') <> (RECEIVED_DATE IS NOT NULL AND QTY_RECEIVED IS NOT NULL)), FALSE
    FROM RAW.ERP_PURCHASE_ORDER_LINES
  UNION ALL SELECT 'RAW', 'Dates in order (ordered <= expected, received not in future)', 'ERP_PURCHASE_ORDER_LINES',
         COUNT_IF(EXPECTED_DATE < ORDER_DATE OR RECEIVED_DATE > CURRENT_DATE() OR ORDER_DATE > CURRENT_DATE()), FALSE
    FROM RAW.ERP_PURCHASE_ORDER_LINES
  UNION ALL SELECT 'RAW', 'Received qty within 0-100% of ordered', 'ERP_PURCHASE_ORDER_LINES',
         COUNT_IF(QTY_RECEIVED < 0 OR QTY_RECEIVED > QTY_ORDERED), FALSE FROM RAW.ERP_PURCHASE_ORDER_LINES
  UNION ALL SELECT 'RAW', 'Delivered shipments have an arrival date; others do not', 'TMS_SHIPMENTS',
         COUNT_IF((SHIPMENT_STATUS = 'DELIVERED') <> (ACTUAL_ARRIVAL IS NOT NULL)), FALSE FROM RAW.TMS_SHIPMENTS
  UNION ALL SELECT 'RAW', 'No negative freight, duty or pallets', 'TMS_SHIPMENTS',
         COUNT_IF(FREIGHT_COST_GBP < 0 OR DUTY_COST_GBP < 0 OR PALLETS <= 0), FALSE FROM RAW.TMS_SHIPMENTS
  UNION ALL SELECT 'RAW', 'Warehouse costs only for closed months', 'FIN_WAREHOUSE_COSTS_MONTHLY',
         COUNT_IF(PERIOD_MONTH >= DATE_TRUNC('month', CURRENT_DATE())), FALSE FROM RAW.FIN_WAREHOUSE_COSTS_MONTHLY

  -- ---------------------------------------------------------------- staging reconciles to raw
  UNION ALL SELECT 'STAGING', 'Row count matches RAW', 'STG_STOCK_SNAPSHOTS',
         ABS((SELECT COUNT(*) FROM STAGING.STG_STOCK_SNAPSHOTS) - (SELECT COUNT(*) FROM RAW.WMS_STOCK_SNAPSHOT_DAILY)), FALSE
  UNION ALL SELECT 'STAGING', 'Row count matches RAW', 'STG_SALES',
         ABS((SELECT COUNT(*) FROM STAGING.STG_SALES) - (SELECT COUNT(*) FROM RAW.POS_SALES_DAILY)), FALSE
  UNION ALL SELECT 'STAGING', 'Row count matches RAW', 'STG_PURCHASE_ORDER_LINES',
         ABS((SELECT COUNT(*) FROM STAGING.STG_PURCHASE_ORDER_LINES) - (SELECT COUNT(*) FROM RAW.ERP_PURCHASE_ORDER_LINES)), FALSE
  UNION ALL SELECT 'STAGING', 'Row count matches RAW', 'STG_SHIPMENTS',
         ABS((SELECT COUNT(*) FROM STAGING.STG_SHIPMENTS) - (SELECT COUNT(*) FROM RAW.TMS_SHIPMENTS)), FALSE
  UNION ALL SELECT 'STAGING', 'Net sales total matches RAW (GBP pence)', 'STG_SALES',
         ROUND(ABS((SELECT SUM(NET_SALES_GBP) FROM STAGING.STG_SALES) - (SELECT SUM(NET_SALES_GBP) FROM RAW.POS_SALES_DAILY)) * 100), FALSE
  UNION ALL SELECT 'STAGING', 'Staging is a table (not a view)', 'STAGING schema', COUNT(*), FALSE
    FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = 'STAGING' AND TABLE_TYPE <> 'BASE TABLE'

  -- ---------------------------------------------------------------- marts (dbt singular tests)
  UNION ALL SELECT 'MARTS', 'Units sold <= units demanded (dbt test)', 'FCT_INVENTORY_DAILY',
         COUNT_IF(UNITS_SOLD > UNITS_DEMANDED), FALSE FROM MARTS.FCT_INVENTORY_DAILY
  UNION ALL SELECT 'MARTS', 'Orders respect MOQ (dbt test)', 'RPT_INVENTORY_POSITION',
         COUNT_IF(RECOMMENDED_ORDER_QTY > 0 AND MOD(RECOMMENDED_ORDER_QTY, MIN_ORDER_QTY) <> 0), FALSE FROM MARTS.RPT_INVENTORY_POSITION
  UNION ALL SELECT 'MARTS', 'Customer sales reconcile to site sales (dbt test)', 'FCT_CUSTOMER_SALES_DAILY', COUNT(*), FALSE
    FROM STAGING.STG_SALES s
    JOIN MARTS.DIM_PRODUCT p ON p.SKU = s.SKU
    LEFT JOIN (SELECT SALES_DATE, WAREHOUSE_CODE, SKU, SUM(NET_SALES_GBP) AS NET_SALES_GBP
                 FROM MARTS.FCT_CUSTOMER_SALES_DAILY GROUP BY 1, 2, 3) a
      ON a.SALES_DATE = s.SALES_DATE AND a.WAREHOUSE_CODE = s.WAREHOUSE_CODE AND a.SKU = s.SKU
   WHERE ABS(s.NET_SALES_GBP - COALESCE(a.NET_SALES_GBP, 0)) > 0.01
  UNION ALL SELECT 'MARTS', 'Marts current to yesterday', 'FCT_INVENTORY_DAILY',
         IFF(MAX(SNAPSHOT_DATE) >= DATEADD(day, -1, CURRENT_DATE()), 0, 1), FALSE FROM MARTS.FCT_INVENTORY_DAILY
  UNION ALL SELECT 'MARTS', 'Unique grain (date, site, SKU)', 'FCT_INVENTORY_DAILY',
         COUNT(*) - COUNT(DISTINCT SNAPSHOT_DATE, WAREHOUSE_CODE, SKU), FALSE FROM MARTS.FCT_INVENTORY_DAILY
)
SELECT layer, check_name, table_name, failing_rows,
       IFF(failing_rows = 0, 'PASS', IFF(warn_only, 'WARN', 'FAIL')) AS status
FROM checks
ORDER BY DECODE(status, 'FAIL', 0, 'WARN', 1, 2), DECODE(layer, 'RAW', 0, 'STAGING', 1, 2), table_name, check_name;
