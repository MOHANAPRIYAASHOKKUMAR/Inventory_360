"""Render the dbt_inventory models to plain Snowflake DDL.

Fallback deployment path for environments where dbt cannot authenticate
(for example SSO-only accounts without a PAT or key-pair). Reproduces the
subset of dbt behaviour this project uses: ref(), source(), var(), config()
and the project macros. Output is written in dependency order.

Usage:
    python scripts/render_dbt_models.py > sql/deployment/02_dbt_models_rendered.sql
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import jinja2
import yaml

ROOT = Path(__file__).resolve().parents[1]
DBT_DIR = ROOT / "dbt_inventory"
DATABASE = "INVENTORY_360_DB"


def load_project() -> dict:
    return yaml.safe_load((DBT_DIR / "dbt_project.yml").read_text())


def discover_models() -> dict[str, dict]:
    """Layer from the folder; materialisation from dbt_project.yml (``+materialized`` per layer)."""
    layers = load_project()["models"]["inventory_360"]
    models = {}
    for path in sorted((DBT_DIR / "models").rglob("*.sql")):
        key = "staging" if "staging" in path.parts else "marts"
        layer = layers[key]["+schema"]
        materialized = layers[key].get("+materialized", "view").upper()
        models[path.stem] = {"path": path, "schema": layer, "materialized": materialized}
    return models


def build_env(project: dict, models: dict[str, dict]) -> jinja2.Environment:
    env = jinja2.Environment(undefined=jinja2.StrictUndefined)
    macro_src = "\n".join(p.read_text() for p in sorted((DBT_DIR / "macros").glob("*.sql")))
    macros = env.from_string(macro_src).module

    def ref(name: str) -> str:
        m = models[name]
        return f"{DATABASE}.{m['schema']}.{name.upper()}"

    def source(src: str, table: str) -> str:
        return f"{DATABASE}.{src.upper()}.{table.upper()}"

    variables = project.get("vars", {})
    env.globals.update(
        ref=ref,
        source=source,
        var=lambda k, default=None: variables.get(k, default),
        config=lambda **_: "",
        safe_divide=macros.safe_divide,
        uk_fiscal_year=macros.uk_fiscal_year,
    )
    return env


def dependency_order(models: dict[str, dict]) -> list[str]:
    deps = {
        name: set(re.findall(r"ref\(\s*['\"](\w+)['\"]\s*\)", m["path"].read_text()))
        for name, m in models.items()
    }
    ordered, seen = [], set()

    def visit(n: str) -> None:
        if n in seen:
            return
        seen.add(n)
        for d in sorted(deps[n]):
            visit(d)
        ordered.append(n)

    for n in sorted(models):
        visit(n)
    return ordered


def main() -> None:
    project = load_project()
    models = discover_models()
    env = build_env(project, models)
    out = ["-- Generated by scripts/render_dbt_models.py - do not edit by hand"]
    for name in dependency_order(models):
        m = models[name]
        body = env.from_string(m["path"].read_text()).render().strip().rstrip(";")
        keys = re.search(r"cluster_by\s*=\s*\[([^\]]*)\]", m["path"].read_text())
        cluster = f" CLUSTER BY ({', '.join(k.strip(chr(39) + chr(34) + ' ') for k in keys.group(1).split(','))})" if keys else ""
        out.append(
            f"\n-- {m['path'].relative_to(ROOT).as_posix()}\n"
            f"CREATE OR REPLACE {m['materialized']} {DATABASE}.{m['schema']}.{name.upper()}{cluster} AS\n{body};"
        )
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
